import { comServidorDeTelas } from "./servidor-telas.mjs";
import { BASE } from "./percorrer-telas.mjs";
import { instalarBancoFalso } from "./banco-falso.mjs";
import { carregarChromium } from "./playwright.mjs";
const OUT = "/tmp/claude-0/-home-user/af7e976b-db09-5396-8fcb-cfdd51481c2f/scratchpad/";
process.exit(await comServidorDeTelas(async () => {
  const chromium = await carregarChromium();
  const nav = await chromium.launch({ args: ["--lang=pt-BR"] });
  const ctx = await nav.newContext({ viewport: { width: 1600, height: 1000 }, deviceScaleFactor: 2, locale: "pt-BR", timezoneId: "America/Sao_Paulo" });
  await instalarBancoFalso(ctx);
  const p = await ctx.newPage();
  await p.goto(BASE, { waitUntil: "networkidle" });
  await p.fill('input[type="text"], input:not([type="password"]):visible', "demo");
  await p.fill('input[type="password"]', "demo1234");
  await p.click('button[type="submit"]');
  await p.waitForTimeout(2500);
  await p.goto(`${BASE}/#/configuracoes`, { waitUntil: "networkidle" });
  await p.waitForTimeout(1600);
  await p.locator("button").filter({ hasText: "Dados fiscais da loja" }).first().click();
  await p.waitForTimeout(900);
  const campo = p.getByLabel("Percentual aproximado dos tributos do Simples (%)");
  await campo.fill("150");
  const botao = p.getByRole("button", { name: "Salvar dados fiscais" });
  await botao.click();
  await p.waitForTimeout(700);
  await botao.scrollIntoViewIfNeeded();
  const frase = p.getByText("Não salvou: confira o percentual");
  console.log("frase visivel antes:", await frase.count());
  await botao.locator("xpath=..").screenshot({ path: OUT + "print-866-erro-botao.png" });
  await p.getByLabel("Regime tributário").selectOption("lucro_presumido");
  await p.waitForTimeout(500);
  console.log("frase depois:", await frase.count(), "| campo depois:", await campo.count(), "| alerta:", await p.getByRole("alert").count());
  await nav.close();
  return 0;
}));
